#include <stdio.h>
int main(){
    // ++ incrementa de 1
    // -- decrementa de 1

    int numero = 10;
    printf("Incremento = %i\n", ++numero);
    printf("Decremento = %i\n", --numero);
    printf("Pos-Incremento = %i\n", numero++);
    printf("Pos-decremento = %i\n", numero--);

    
    return 0;
}