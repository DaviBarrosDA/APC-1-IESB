#include <stdio.h>

int main() {

    printf("Contagem crescente: ");
    for(int i = 0; i < 10; i++) {
        printf("%i ", i);
    }
    printf("\n");


    printf("Contagem decrescente: ");
    for(int i = 9; i >= 0; i--) {
        printf("%i ", i);
    }
    printf("\n");

  
    
    
    return 0;
}